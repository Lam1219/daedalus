#!/bin/sh
# Generates Daedalus/App/SupabaseConfig.generated.swift from ../daedalus-companion/supabase.properties.
# Without that file the app builds, and sign-in shows as "not set up".
DIR="$(cd "$(dirname "$0")/.." && pwd)"
PROPS="$DIR/../daedalus-companion/supabase.properties"
OUT="$DIR/Daedalus/App/SupabaseConfig.generated.swift"
URL=""; KEY=""
if [ -f "$PROPS" ]; then
  URL=$(grep '^SUPABASE_URL=' "$PROPS" | cut -d= -f2- | tr -d '\r')
  KEY=$(grep '^SUPABASE_ANON_KEY=' "$PROPS" | cut -d= -f2- | tr -d '\r')
else
  echo "warning: supabase.properties not found; sign-in will show as not set up"
fi
NEW=$(printf '// Generated by tools/supabase_config.sh from supabase.properties. Not committed.\nenum SupabaseConfig {\n    static let url = "%s"\n    static let anonKey = "%s"\n}\n' "$URL" "$KEY")
# Only rewrite when it changed, so Xcode doesn't recompile every time.
[ -f "$OUT" ] && [ "$(cat "$OUT")" = "$NEW" ] || printf '%s\n' "$NEW" > "$OUT"
